--
-- Paste this whole file into the Supabase SQL Editor and press Run.
-- It is safe to run again: everything is created only if missing.
--
-- BEFORE RUNNING: replace you@example.com near the bottom with your own
-- email address, so you are the first person on the family list. Everyone
-- else can be added from inside the app (gear icon → Family).

create extension if not exists pgcrypto;

-- Who may use the journal. Signing in only proves someone owns an email
-- address; being on this list is what lets them see and write entries.
create table if not exists public.members (
  email    text primary key check (email = lower(email) and position('@' in email) > 1),
  name     text not null default '',
  added_by text default lower(auth.jwt() ->> 'email'),
  added_at timestamptz not null default now()
);

create or replace function public.is_member()
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.members where email = lower(auth.jwt() ->> 'email')
  );
$$;

revoke all on function public.is_member() from public, anon;
grant execute on function public.is_member() to authenticated;

create table if not exists public.entries (
  id           uuid primary key default gen_random_uuid(),
  entry_date   date not null,
  entry_time   time,
  title        text not null default '' check (length(title) <= 200),
  body         text not null default '' check (length(body) <= 50000),
  people       text[] not null default '{}',
  activities   text[] not null default '{}',
  author_email text not null default lower(auth.jwt() ->> 'email'),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists public.photos (
  id         uuid primary key default gen_random_uuid(),
  entry_id   uuid not null references public.entries (id) on delete cascade,
  path       text not null unique,
  thumb_path text not null unique,
  width      int,
  height     int,
  added_by   text default lower(auth.jwt() ->> 'email'),
  created_at timestamptz not null default now()
);
create index if not exists photos_entry_id on public.photos (entry_id);

-- The choices in the "Who was there?" and "What did we do?" drop-downs.
-- Anyone in the family can add to them or remove from them in the app.
create table if not exists public.options (
  kind     text not null check (kind in ('person', 'activity')),
  label    text not null check (length(label) between 1 and 40),
  position bigint generated by default as identity,
  added_by text default lower(auth.jwt() ->> 'email'),
  primary key (kind, label)
);

-- Row-level security: family members can do everything, nobody else
-- can do anything. The anon key in config.js is public by design; these
-- policies are what keep the journal private.
alter table public.members enable row level security;
alter table public.entries enable row level security;
alter table public.photos  enable row level security;
alter table public.options enable row level security;

do $$
declare t text;
begin
  foreach t in array array['members', 'entries', 'photos', 'options'] loop
    execute format('drop policy if exists "family only" on public.%I', t);
    execute format(
      'create policy "family only" on public.%I for all to authenticated
         using (public.is_member()) with check (public.is_member())', t);
  end loop;
end $$;

-- Photos live in a private bucket; the app shows them through
-- short-lived signed links.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('photos', 'photos', false, 5242880, array['image/jpeg'])
on conflict (id) do nothing;

drop policy if exists "family reads photos" on storage.objects;
drop policy if exists "family adds photos" on storage.objects;
drop policy if exists "family removes photos" on storage.objects;
create policy "family reads photos" on storage.objects for select to authenticated
  using (bucket_id = 'photos' and public.is_member());
create policy "family adds photos" on storage.objects for insert to authenticated
  with check (bucket_id = 'photos' and public.is_member());
create policy "family removes photos" on storage.objects for delete to authenticated
  using (bucket_id = 'photos' and public.is_member());

